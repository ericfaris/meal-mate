#!/usr/bin/env node
/**
 * Reads frontend/src/theme/index.ts (the single source of truth for design
 * tokens) and emits frontend/public/design-tokens.css — CSS custom
 * properties with the exact same values, consumed by
 * frontend/public/design-system.html (the static showcase page).
 *
 * This is a small regex-based extractor, not a TS compiler: it expects the
 * theme file's existing shape (flat `key: 'value',` / `key: number,` lines
 * inside named `export const X = { ... };` blocks). If you restructure
 * theme/index.ts, update the block names/regex below to match, then rerun:
 *
 *   node frontend/scripts/generate-design-tokens-css.js
 *
 * Run this after any change to theme/index.ts's values — see DESIGN.md
 * "Keeping tokens in sync". Node, no dependencies.
 */
const fs = require('fs');
const path = require('path');

const themePath = path.join(__dirname, '..', 'src', 'theme', 'index.ts');
const outPath = path.join(__dirname, '..', 'public', 'design-tokens.css');
const src = fs.readFileSync(themePath, 'utf8');

function extractBlock(name) {
  const re = new RegExp(`export const ${name} = \\{([\\s\\S]*?)\\n\\};`, 'm');
  const m = src.match(re);
  if (!m) throw new Error(`Could not find block "${name}" in theme/index.ts`);
  return m[1];
}

function extractFlatPairs(block) {
  // Matches `  key: 'value',` or `  key: 123,` at the top level of a block
  // (ignores nested `{ ... }` sub-objects and comment-only lines).
  const pairs = [];
  const lines = block.split('\n');
  let depth = 0;
  for (const line of lines) {
    const opens = (line.match(/\{/g) || []).length;
    const closes = (line.match(/\}/g) || []).length;
    if (depth === 0) {
      const m = line.match(/^\s*([A-Za-z0-9_]+):\s*'([^']*)'/) || line.match(/^\s*([A-Za-z0-9_]+):\s*(-?\d+(?:\.\d+)?)/);
      if (m) pairs.push([m[1], m[2]]);
    }
    depth += opens - closes;
  }
  return pairs;
}

function extractNestedNumber(block, objName, key) {
  const re = new RegExp(`${objName}:\\s*\\{[\\s\\S]*?${key}:\\s*(-?\\d+(?:\\.\\d+)?)`);
  const m = block.match(re);
  return m ? m[1] : null;
}

function extractScaleStep(scaleBlock, step) {
  const re = new RegExp(`${step}:\\s*\\{([\\s\\S]*?)\\n\\s*\\},`);
  const m = scaleBlock.match(re);
  if (!m) return null;
  const body = m[1];
  const font = body.match(/fontFamily:\s*'([^']+)'/);
  const size = body.match(/fontSize:\s*(\d+)/);
  const lh = body.match(/lineHeight:\s*(\d+)/);
  const ls = body.match(/letterSpacing:\s*(-?\d+(?:\.\d+)?)/);
  return {
    fontFamily: font ? font[1] : '',
    fontSize: size ? size[1] : '',
    lineHeight: lh ? lh[1] : '',
    letterSpacing: ls ? ls[1] : '0',
  };
}

const colors = extractFlatPairs(extractBlock('colors'));
const spacing = extractFlatPairs(extractBlock('spacing'));
const borderRadius = extractFlatPairs(extractBlock('borderRadius'));
const heights = extractFlatPairs(extractBlock('heights'));
const animations = extractFlatPairs(extractBlock('animations'));

const typographyBlock = extractBlock('typography');
const scaleMatch = typographyBlock.match(/scale:\s*\{([\s\S]*?)\n\s*\},\n\s*\/\//);
const scaleBlock = scaleMatch ? scaleMatch[1] : typographyBlock;
const steps = ['display', 'h1', 'h2', 'h3', 'body', 'small', 'tiny'];
const scale = steps.map((s) => ({ step: s, ...extractScaleStep(scaleBlock, s) })).filter((s) => s.fontSize);

const shadowsBlock = extractBlock('shadows');
const shadowNames = ['card', 'button', 'floating'];
const shadows = shadowNames.map((name) => {
  const offsetY = extractNestedNumber(shadowsBlock, name, 'height') || '0';
  const opacity = extractNestedNumber(shadowsBlock, name, 'shadowOpacity') || '0.1';
  const radius = extractNestedNumber(shadowsBlock, name, 'shadowRadius') || '4';
  return { name, offsetY, opacity, radius };
});

const motionBlock = extractBlock('motion');
const motionNames = ['microInteraction', 'reveal', 'emphasis'];
const motion = motionNames.map((name) => {
  const re = new RegExp(`${name}:\\s*\\{[\\s\\S]*?duration:\\s*([A-Za-z.]+),[\\s\\S]*?cubicBezier:\\s*'([^']+)'`);
  const m = motionBlock.match(re);
  let duration = m ? m[1] : '300';
  // duration may reference `animations.fast` etc — resolve against the
  // animations block we already parsed.
  const animRef = duration.match(/animations\.([A-Za-z]+)/);
  if (animRef) {
    const found = animations.find(([k]) => k === animRef[1]);
    duration = found ? found[1] : '300';
  }
  return { name, duration, cubicBezier: m ? m[2] : 'ease' };
});

function cssVarName(prefix, key) {
  return `--${prefix}-${key.replace(/([A-Z])/g, '-$1').toLowerCase()}`;
}

let css = `/**
 * AUTO-GENERATED by frontend/scripts/generate-design-tokens-css.js
 * from frontend/src/theme/index.ts — do not hand-edit.
 * Regenerate with: node frontend/scripts/generate-design-tokens-css.js
 */
:root {
  /* Color */
`;
for (const [key, value] of colors) {
  css += `  ${cssVarName('color', key)}: ${value};\n`;
}
css += `\n  /* Spacing */\n`;
for (const [key, value] of spacing) {
  css += `  ${cssVarName('space', key)}: ${value}px;\n`;
}
css += `\n  /* Radius */\n`;
for (const [key, value] of borderRadius) {
  css += `  ${cssVarName('radius', key)}: ${value === '999' ? '999px' : value + 'px'};\n`;
}
css += `\n  /* Heights */\n`;
for (const [key, value] of heights) {
  css += `  ${cssVarName('height', key)}: ${value}px;\n`;
}
css += `\n  /* Motion durations (ms) */\n`;
for (const m of motion) {
  css += `  --motion-${m.name.replace(/([A-Z])/g, '-$1').toLowerCase()}-duration: ${m.duration}ms;\n`;
  css += `  --motion-${m.name.replace(/([A-Z])/g, '-$1').toLowerCase()}-easing: ${m.cubicBezier};\n`;
}
css += `\n  /* Shadows */\n`;
for (const s of shadows) {
  css += `  --shadow-${s.name}: 0 ${s.offsetY}px ${s.radius}px rgba(0, 0, 0, ${s.opacity});\n`;
}
css += `\n  /* Type scale */\n`;
for (const s of scale) {
  css += `  --type-${s.step}-font: '${s.fontFamily.replace('-Regular', '')}', ${s.fontFamily.startsWith('Fraunces') ? 'Georgia, serif' : '-apple-system, sans-serif'};\n`;
  css += `  --type-${s.step}-size: ${s.fontSize}px;\n`;
  css += `  --type-${s.step}-line-height: ${s.lineHeight}px;\n`;
  css += `  --type-${s.step}-letter-spacing: ${s.letterSpacing}px;\n`;
}
css += `}\n`;

fs.writeFileSync(outPath, css);
console.log(`[design-tokens] wrote ${outPath}`);
console.log(`[design-tokens] ${colors.length} colors, ${spacing.length} spacing steps, ${scale.length} type steps, ${shadows.length} shadows, ${motion.length} motion tokens`);
